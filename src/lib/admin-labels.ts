export function adminStateLabel(value: string | number | null | undefined) {
  const key = String(value ?? "");
  return Object.hasOwn(adminStates, key) ? adminStates[key] : key || "—";
}
export function adminFieldLabel(name: string) {
  return Object.hasOwn(adminFields, name) ? adminFields[name] : name;
}
